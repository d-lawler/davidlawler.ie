#!/usr/bin/env python3
"""Shrinks the source media in visuals-assets/ for the /visuals page.

    python3 scripts/build-visuals.py

Reads   visuals-assets/images/*.png|jpg|webp   (stills, e.g. exported from Figma)
        visuals-assets/videos/**/*.mp4|mov     (screen recordings)
Writes  public/visuals-media/<name>.webp             (stills, at most 1000px on the long edge)
        public/visuals-media/<name>.mp4 + .webp      (silent 8-second loops and their first frame)
        app/utils/visuals.ts                   (the list the page reads)

To take something off the page, move its file out of those two folders and run
this again. A still with the same name as a video is skipped: it is a frame of
that video. A leading "012_" on a file name is only there for sorting.

visuals-assets/ is not in the repo: the sources are large. Needs ImageMagick
(magick) and ffmpeg.
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'visuals-assets'
OUT = ROOT / 'public' / 'visuals-media'
LIST = ROOT / 'app' / 'utils' / 'visuals.ts'

STILL_EDGE = 1000   # px, long edge
CLIP_EDGE = 720     # px, long edge
CLIP_SECONDS = 8


def run(*args):
    return subprocess.run([str(a) for a in args], check=True, capture_output=True, text=True).stdout


def slug(path):
    name = re.sub(r'^\d+_', '', path.stem).lower()
    return re.sub(r'[^a-z0-9]+', '-', name).strip('-')


def position(path):
    # Where the still sat among the layers of the Figma page. Neighbours there
    # tend to be the same project, which the page uses to keep them apart.
    found = re.match(r'(\d+)_', path.name)
    return int(found.group(1)) if found else 0


def size(path):
    width, height = run('magick', 'identify', '-format', '%w %h', f'{path}[0]').split()
    return int(width), int(height)


def still(source, target):
    if not target.exists() or target.stat().st_mtime < source.stat().st_mtime:
        run('magick', source, '-resize', f'{STILL_EDGE}x{STILL_EDGE}>', '-quality', '78', target)


def clip(source, target, poster):
    if not target.exists() or target.stat().st_mtime < source.stat().st_mtime:
        scale = f"scale='if(gt(iw,ih),min({CLIP_EDGE},iw),-2)':'if(gt(iw,ih),-2,min({CLIP_EDGE},ih))'"
        run('ffmpeg', '-y', '-loglevel', 'error', '-i', source, '-t', CLIP_SECONDS, '-an',
            '-vf', f'{scale},fps=24', '-c:v', 'libx264', '-crf', '30', '-preset', 'slow',
            '-pix_fmt', 'yuv420p', '-movflags', '+faststart', target)
        run('ffmpeg', '-y', '-loglevel', 'error', '-i', target, '-frames:v', '1', '-quality', '78', poster)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    items, made = [], set()

    images = sorted(p for p in (SOURCE / 'images').iterdir() if p.suffix.lower() in ('.png', '.jpg', '.jpeg', '.webp'))
    places = {slug(p): position(p) for p in reversed(images)}

    videos = sorted(p for p in (SOURCE / 'videos').rglob('*') if p.suffix.lower() in ('.mp4', '.mov'))
    for source in videos:
        name = slug(source)
        if name in made:
            continue
        clip(source, OUT / f'{name}.mp4', OUT / f'{name}.webp')
        width, height = size(OUT / f'{name}.webp')
        items.append({'src': f'/visuals-media/{name}.webp', 'video': f'/visuals-media/{name}.mp4', 'width': width, 'height': height, 'place': places.get(name, 0)})
        made.add(name)

    clips = set(made)
    for source in images:
        name = slug(source)
        if name in clips:
            continue
        # Two stills can share a layer name: both are kept.
        base, count = name, 1
        while name in made:
            count += 1
            name = f'{base}-{count}'
        still(source, OUT / f'{name}.webp')
        width, height = size(OUT / f'{name}.webp')
        items.append({'src': f'/visuals-media/{name}.webp', 'width': width, 'height': height, 'place': position(source)})
        made.add(name)

    # Anything left in public/visuals-media from an earlier run that is no longer wanted.
    wanted = {f'{name}.webp' for name in made} | {f'{name}.mp4' for name in made}
    for old in OUT.iterdir():
        if old.name not in wanted:
            old.unlink()

    lines = [
        '// Generated by scripts/build-visuals.py from visuals-assets/. Do not edit by hand.',
        '',
        'export interface Visual {',
        '    // The image, or the first frame of a video.',
        '    src: string',
        '    // A short silent loop, where there is one.',
        '    video?: string',
        '    width: number',
        '    height: number',
        '    // Its position among the layers of the Figma page it came from. Close',
        '    // numbers are usually the same project.',
        '    place: number',
        '}',
        '',
        'export const visuals: Visual[] = [',
    ]
    for item in items:
        fields = ', '.join(f'{key}: {json.dumps(value)}' for key, value in item.items())
        lines.append('    { ' + fields.replace('"', "'") + ' },')
    lines += [']', '']
    LIST.write_text('\n'.join(lines))

    total = sum(f.stat().st_size for f in OUT.iterdir())
    clips = sum(1 for item in items if 'video' in item)
    print(f'{len(items)} visuals ({clips} videos), {total / 1e6:.1f} MB in public/visuals-media')


if __name__ == '__main__':
    main()
